import { readFileSync, statSync } from 'node:fs'
import { resolve } from 'node:path'
import type { Plugin } from 'vite'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { NotFoundPage } from '../src/features/not-found/NotFoundPage'
import {
  BROWSER_CHALLENGES,
  browserChallengePath,
} from '../src/features/challenges/browser-challenges'
import {
  metaTags,
  pageMeta,
  PUBLIC_META,
  ROUTE_META,
  SITE_URL,
  type PageMeta,
} from '../src/shared/seo'

const STATIC_META: Record<string, PageMeta> = {
  ...PUBLIC_META,
  '/login': pageMeta('login'),
  '/play/game': pageMeta('game'),
  '/play/limited': pageMeta('limited'),
  '/decks': pageMeta('decks'),
  ...Object.fromEntries(
    BROWSER_CHALLENGES.map((challenge) => [
      browserChallengePath(challenge.id),
      pageMeta('browser-challenge', { challengeId: challenge.id }),
    ]),
  ),
}

/** Initial HTML must describe a valid route before the app has loaded. */
export function initialPageMeta(pathname: string, development = false): PageMeta {
  const path =
    (pathname === '/index.html' ? '/' : pathname.replace(/\.html$/, '')).replace(/\/$/, '') || '/'
  if (Object.hasOwn(STATIC_META, path)) {
    return STATIC_META[path]!
  }
  if (/^\/(decks|match)\/[^/]+$/.test(path)) {
    return pageMeta('private')
  }
  if (
    path === '/challenge/random' ||
    /^\/challenge\/[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/.test(path)
  ) {
    return pageMeta('browser-challenge')
  }
  if (development && /^\/(dev|challenges)(\/|$)/.test(path)) {
    return pageMeta('private')
  }
  return pageMeta('not-found')
}

function escapeHtml(value: string): string {
  return value.replace(
    /[&<>"']/g,
    (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]!,
  )
}

function htmlFile(path: string): string {
  return path === '/' ? 'index.html' : `${path.slice(1)}.html`
}

export function renderHtml(template: string, meta: PageMeta): string {
  const tags = Object.entries(metaTags(meta)).map(
    ([name, content]) =>
      `<meta ${name.startsWith('og:') ? 'property' : 'name'}="${name}" content="${escapeHtml(content)}" />`,
  )
  const head = [
    `<title>${escapeHtml(meta.title)}</title>`,
    ...tags,
    ...(meta.canonical ? [`<link rel="canonical" href="${escapeHtml(meta.canonical)}" />`] : []),
  ].join('\n    ')
  const path = meta.canonical ? new URL(meta.canonical).pathname : ''
  const heading =
    path === '/about'
      ? 'A seat at the table. Any time.'
      : path === '/roadmap'
        ? 'What’s next at the table.'
        : path === '/'
          ? 'Your favourite card game, ready when you are.'
          : meta.title
  // React replaces this introduction when the interactive app mounts.
  const content =
    meta === pageMeta('not-found')
      ? renderToStaticMarkup(createElement(NotFoundPage))
      : `<div class="public-theme public-static"><main class="public-static-content">
    <h1>${escapeHtml(heading)}</h1>
    <p>${escapeHtml(meta.description)}</p>
    ${path === '/' || path === '/about' ? '<p>Sign in with an email code to save your decks. Imports use the pinned Forge card catalog. Desktop is the best experience while mobile layouts are refined.</p>' : ''}
    <nav aria-label="Site navigation"><a href="/">Live table</a> · <a href="/roadmap">Roadmap</a> · <a href="/about">About</a> · <a href="/login">Sign in to play</a></nav>
    <noscript><p>Enable JavaScript to watch games and play.</p></noscript>
  </main></div>`
  return template
    .replace(
      /<!-- seo:head -->[\s\S]*?<!-- \/seo:head -->/,
      `<!-- seo:head -->\n    ${head}\n    <!-- /seo:head -->`,
    )
    .replace(
      /<!-- seo:content -->[\s\S]*?<!-- \/seo:content -->/,
      `<!-- seo:content -->${content}<!-- /seo:content -->`,
    )
}

export function sitemap(): string {
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${Object.values(
    PUBLIC_META,
  )
    .map((meta) => `  <url><loc>${escapeHtml(meta.canonical!)}</loc></url>`)
    .join('\n')}\n</urlset>\n`
}

/** Include inside the static edge's server block. No blanket SPA fallback. */
export function nginxRoutes(): string {
  const pages = Object.keys(STATIC_META)
    .map((path) => {
      const file = htmlFile(path)
      return [
        `location = ${path} { try_files /${file} =404; }`,
        `location = /${file} { return 308 ${path}$is_args$args; }`,
        ...(path === '/' ? [] : [`location = ${path}/ { return 308 ${path}$is_args$args; }`]),
      ].join('\n')
    })
    .join('\n')
  return `# Generated by the Vite SEO build.\n${pages}
location ~ ^/(decks|match)/[^/]+/?$ { try_files /private.html =404; }
location ~ "^/challenge/(random|[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12})/?$" { try_files /private.html =404; }
location = /private.html { internal; }
location = /404.html { internal; }
location = /seo-routes.conf { return 404; }
error_page 404 /404.html;
location / { try_files $uri =404; }
`
}

export function seo(): Plugin {
  return {
    name: 'forge-web-seo',
    enforce: 'post',
    transformIndexHtml: {
      order: 'post',
      handler(html, context) {
        const path =
          new URL(context.originalUrl ?? '/', SITE_URL).pathname.replace(/\/$/, '') || '/'
        return renderHtml(html, initialPageMeta(path, Boolean(context.server)))
      },
    },
    generateBundle(_options, bundle) {
      const index = bundle['index.html']
      if (index?.type !== 'asset') {
        throw new Error('SEO build requires index.html')
      }
      const template = String(index.source)
      for (const [path, meta] of Object.entries(STATIC_META)) {
        if (path === '/') {
          continue
        }
        this.emitFile({
          type: 'asset',
          fileName: htmlFile(path),
          source: renderHtml(template, meta),
        })
      }
      for (const [fileName, meta] of [
        ['private.html', ROUTE_META['private']!],
        ['404.html', pageMeta('not-found')],
      ] as const) {
        this.emitFile({ type: 'asset', fileName, source: renderHtml(template, meta) })
      }
      this.emitFile({ type: 'asset', fileName: 'sitemap.xml', source: sitemap() })
      this.emitFile({ type: 'asset', fileName: 'seo-routes.conf', source: nginxRoutes() })
    },
    configurePreviewServer(server) {
      const dir = resolve(server.config.root, server.config.build.outDir)
      server.middlewares.use((req, res, next) => {
        if (req.method !== 'GET' && req.method !== 'HEAD') {
          return next()
        }
        const url = new URL(req.url ?? '/', SITE_URL)
        const path = url.pathname
        if (path === '/api' || path.startsWith('/api/') || path === '/gre') {
          return next()
        }
        const canonicalPath = path.endsWith('.html')
          ? path === '/index.html'
            ? '/'
            : path.slice(0, -5)
          : path.replace(/\/$/, '') || '/'
        if (Object.hasOwn(STATIC_META, canonicalPath) && canonicalPath !== path) {
          res.writeHead(308, { Location: canonicalPath + url.search }).end()
          return
        }
        const isPrivate =
          /^\/(decks|match)\/[^/]+\/?$/.test(path) ||
          /^\/challenge\/(random|[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12})\/?$/.test(path)
        const file = Object.hasOwn(STATIC_META, path)
          ? htmlFile(path)
          : isPrivate
            ? 'private.html'
            : null
        // Existing assets pass through; unknown URLs never reach Vite's SPA fallback.
        if (!file && !['/private.html', '/404.html', '/seo-routes.conf'].includes(path)) {
          try {
            const asset = resolve(dir, `.${decodeURIComponent(path)}`)
            if (
              asset.startsWith(`${dir}/`) &&
              statSync(asset, { throwIfNoEntry: false })?.isFile()
            ) {
              if (path.startsWith('/browser-engine/') && url.searchParams.has('v')) {
                res.setHeader('Cache-Control', 'private, max-age=300')
              }
              return next()
            }
          } catch {
            /* Malformed paths receive the same 404 as missing assets. */
          }
        }
        res.statusCode = file ? 200 : 404
        res.setHeader('Content-Type', 'text/html; charset=utf-8')
        res.end(req.method === 'HEAD' ? undefined : readFileSync(resolve(dir, file ?? '404.html')))
      })
    },
  }
}
